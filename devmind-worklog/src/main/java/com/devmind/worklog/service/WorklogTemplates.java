package com.devmind.worklog.service;

import java.util.Map;

/**
 * CAP-41 FR-05 报告格式模板：内置默认模板 + 占位符渲染。
 *
 * <p>占位符：{{date}}（日报日期）/ {{weekRange}}（周报周区间）/ {{entries}}（条目/日报清单）
 * / {{commits}}（git 提交清单）。用户自定义模板存 worklog_user_settings.daily_template_md
 * / weekly_template_md（空白 = 回退内置默认）。渲染发生在生成 prompt 时（服务端），
 * 渲染结果同时进会话 prompt 与上下文包 CLAUDE.md「当前任务」节。</p>
 *
 * <p>内置模板即会话 prompt 全文（不再追加协议文本），所以写作口径全部写在这里；素材清单
 * （{{entries}}/{{commits}}）由 {@link ReportPrompts} 填充。口径：先归纳主题再写产出
 * （对象 + 动作 + 结果/影响），禁止按提交/条目/日期逐条罗列；不列 commit sha，
 * 非计划事项收「计划外工作」。模板内附正反示例与成稿自查清单，抑制「流水账」式改写。</p>
 */
public final class WorklogTemplates {

    /** 内置日报模板（周报分节标题与 {@link ReportService#splitWeekly} 解析约定联动，改动需同步） */
    public static final String DEFAULT_DAILY = """
            # {{date}} 工作日报

            你在写一份提交给团队的个人工作日报。下方素材是当天的事实依据，不是写作模板：
            不要逐条改写素材，先归纳主题，再按产出写。

            ## 写作要求

            1. 先归纳再动笔：同一模块/需求/主题的提交与条目合并成一条，不按提交、条目或时间逐条罗列。
            2. 每条必须写清「对象 + 动作 + 结果/影响」；只有动作、写不出结果的，并入相邻主题并注明「推进中」。
               素材里能得出的数字（完成度、覆盖模块、耗时、修复效果）要保留，不能得出就写结果本身，不要编造。
            3. 结构固定为：**今日重点**（2~3 条最重要的结果）→ **其他进展**（有序列表，按主题补充其余工作）
               → **项目支持**（答疑、临时插单等非计划事项，没有则省略）。同一件事只出现一次，重点与其他进展不重复。
            4. 正文不出现 commit sha；git 提交清单只作事实依据，不照抄其排版。
            5. 全篇条目控制在 8 条以内；「参加例会」这类没有产出的过程性工作不要单独列出。

            ### 示例（只示意写法，不要照抄内容）

            素材：三个提交都属于「登录改造」，另有一条同事答疑。
            流水账写法：1. 修改登录接口 2. 修改登录页面 3. 补充登录测试 4. 解答同事问题。
            合格写法：
            **今日重点**
            - 完成登录改造并补齐回归测试，覆盖账号、验证码与异常分支，登录链路可稳定演示。
            **其他进展**
            1. **登录模块**：重构鉴权接口与前端表单，异常提示统一为可操作文案。
            **项目支持**
            1. 项目支持：协助排查测试环境登录失败问题。

            ## 事实素材（只作依据，不要照抄这里的分条格式）

            ### 当日 git 提交（含提交正文与改动规模）
            {{commits}}

            ### 当日工作条目（含工时与关联需求）
            {{entries}}

            ## 成稿自查（不通过就重写）

            - 是否按提交/条目/时间逐条罗列？是则按主题合并。
            - 每条是否能看出结果或影响，而不是只有动作？
            - 今日重点是否 2~3 条，且没有和其他进展重复？
            - 是否出现 commit sha，或编造了素材里没有的事实？

            正文末尾空一行，写一行：工时合计：X 小时 Y 分钟（按条目分钟数换算；素材无工时可省略）。
            """;

    /**
     * 内置周报模板（「## 上周总结」「## 下周计划」两小节标题是镜像落库的分节解析约定；
     * 「计划外工作」块必须落在上周总结内，否则会被 splitWeekly 切进下周计划）。
     */
    public static final String DEFAULT_WEEKLY = """
            # {{weekRange}} 工作周报

            你在写一份本周工作周报。下方素材是本周的事实依据，不是写作模板：先跨天归纳主题，
            再按产出写，不要按天罗列，也不要把日报逐条搬过来。

            ## 写作要求

            正文恰好包含「## 上周总结」「## 下周计划」两个小节（前端按这两个标题切分落库，
            标题文字不可改，也不要增加其他二级标题）。

            ## 上周总结

            固定结构（小节标题用加粗，不要用二级标题）：
            - **本周重点成果**：3~5 条，每条一句话写清「做了什么 + 结果/影响」，有量化数字就保留；
            - **其他进展**：有序列表，其余工作按模块/主题归并；同一件事跨天合并，只写最终状态；
            - **计划外工作**：项目支持、答疑、临时插单等非计划事项，单独编号列出，不与主线成果混排；
            - **风险与阻塞**（可选）：只写影响下周交付或需要协调的事项，没有则省略。

            要求：已完成写完成，进行中的注明进度；本周没推进的事项不要写进总结；正文不出现 commit sha。

            ## 下周计划

            用有序列表列出 3~6 条，每条一句话，必须能追溯到本周未完成/进行中的线索或周期性工作
            （版本、发版、例行测试等）；写清下周要达成的结果，不要写「继续推进」这类没有指向的空条目。

            ### 示例（只示意结构，不要照抄内容）

            **本周重点成果**
            - 完成工作日志周报生成链路重构，周报可由日报自动归并，人工修订后即可提交。
            **其他进展**
            1. **工作日志·素材**：补齐提交正文与改动规模，生成结果从逐条改写转为按主题归纳。
            **计划外工作**
            1. 项目支持：协助排查测试环境登录失败问题。
            **风险与阻塞**
            - 运行节点偶发离线，定时生成可能延迟到下一批次。

            ### 本周工作记录（日报全文；无日报时为原始条目）
            {{entries}}

            ### 本周 git 提交（仅用于核对日报未覆盖的产出与规模，不要逐条罗列）
            {{commits}}

            ## 成稿自查（不通过就重写）

            - 是否按天或按日报逐条罗列？是则按主题跨天合并。
            - 每条是否能看出结果或影响，而不是只有动作？
            - 计划外工作是否落在「上周总结」内，且没有混进主线成果？
            - 下周计划是否每条都有本周来源，且不是「继续推进」式空话？
            - 是否出现 commit sha，或编造了素材里没有的事实？
            """;

    private WorklogTemplates() {
    }

    /** 用户自定义模板（null/空白 → 内置默认）。 */
    public static String orDefault(String custom, String builtin) {
        return custom == null || custom.isBlank() ? builtin : custom;
    }

    /** 纯字符串替换渲染；未知占位符原样保留（用户写了自己的占位不报错，便于排查）。 */
    public static String render(String template, Map<String, String> vars) {
        String out = template == null ? "" : template;
        for (Map.Entry<String, String> e : vars.entrySet()) {
            out = out.replace("{{" + e.getKey() + "}}", e.getValue() == null ? "" : e.getValue());
        }
        return out;
    }
}
